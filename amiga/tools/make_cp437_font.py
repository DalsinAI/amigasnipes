def load(d):
    glyph = {}
    pat = re.compile(r'\{\s*((?:0x[0-9A-Fa-f]{2}\s*,\s*){7}0x[0-9A-Fa-f]{2})\s*\}')
    for name, start in FILES.items():
        with open(f'{d}/{name}') as f:
            for i, row in enumerate(pat.findall(f.read())):
                glyph.setdefault(start + i, [int(x, 16) for x in row.split(',')])
    with open(f'{d}/font8x8_misc.h') as f:
        for u, row in zip(MISC, pat.findall(f.read())):
            if u is not None:
                glyph.setdefault(u, [int(x, 16) for x in row.split(',')])
    return glyph


def flip(b):  # font8x8 puts the left pixel in bit 0; we put it in bit 7
    return int(f'{b:08b}'[::-1], 2)


def main():
    glyph = load(sys.argv[1])
    out = []
    for c in range(256):
        if c in CONTROL:
            rows = [int(r.replace('#', '1').replace('.', '0'), 2) for r in CONTROL[c]]
        else:
            rows = [flip(b) for b in glyph[ord(bytes([c]).decode('cp437'))]]
        out.append(rows)
    print('/* Code page 437, 8x8, one byte a row, the left pixel in bit 7.')
    print(' * Made by amiga/tools/make_cp437_font.py from font8x8 (Daniel Hepper,')
    print(' * public domain), with the graphic characters it lacks drawn for the')
    print(' * Amiga port (public domain too). */')
    print('static const unsigned char Cp437Font[256][8] =\n{')
    for c, rows in enumerate(out):
        print('\t{' + ', '.join(f'0x{r:02X}' for r in rows) + f'}}, /* 0x{c:02X} */')
    print('};')


if __name__ == '__main__':
    main()
